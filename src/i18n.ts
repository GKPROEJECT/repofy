export function translate(
  language: Language,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) =>
      message.split(`{{${name}}}`).join(String(value)),
    catalogs[language][key] ?? english[key],
  );
}
